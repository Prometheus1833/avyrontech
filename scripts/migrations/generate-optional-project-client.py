"""Build the one-time D1 migration without disabling foreign keys or losing child rows."""
from pathlib import Path
import sqlite3
import re
root = Path(__file__).resolve().parents[2]
db = sqlite3.connect(':memory:')
for path in sorted((root / 'cloudflare/d1/migrations').glob('*.sql')):
    if path.name < '0091_':
        db.executescript(path.read_text())
quote = lambda value: '"' + value.replace('"', '""') + '"'
tables = [r[0] for r in db.execute("SELECT name FROM sqlite_schema WHERE type='table' AND name NOT LIKE 'sqlite_%'")]
affected = {'projects'}
while True:
    expanded = affected | {name for name in tables if any(fk[2] in affected for fk in db.execute('PRAGMA foreign_key_list(' + quote(name) + ')'))}
    if expanded == affected: break
    affected = expanded
children = sorted(affected - {'projects'})
objects = list(db.execute("SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE type IN('trigger','view') AND sql IS NOT NULL ORDER BY type,name"))
objects = [r for r in objects if r[2] in affected or re.search(r'\bprojects\b', r[3], re.I)]
project_sql = db.execute("SELECT sql FROM sqlite_schema WHERE name='projects'").fetchone()[0]
assert 'client_id   TEXT NOT NULL REFERENCES clients' in project_sql
new_sql = project_sql.replace('CREATE TABLE projects', 'CREATE TABLE _project_client_0091', 1).replace('client_id   TEXT NOT NULL REFERENCES clients', 'client_id   TEXT REFERENCES clients', 1)
lines = [
    '-- Allow genuinely unassigned projects; no placeholder client or parallel project store.',
    '-- D1 always enforces foreign keys. Preserve the complete dependent-row closure',
    '-- before rebuilding the parent, including CASCADE, SET NULL and RESTRICT paths.',
    '-- Temporary ordinary tables live only within this atomic migration.',
    '-- Generated by scripts/migrations/generate-optional-project-client.py.',
    'PRAGMA defer_foreign_keys=ON;',
    'CREATE TABLE _project_0091_assert(ok INTEGER NOT NULL CHECK(ok=1));',
]
for name in children:
    lines.append(f'CREATE TABLE {quote("_p0091_"+name)} AS SELECT * FROM {quote(name)};')
for kind,name,_,_ in objects:
    lines.append(f'DROP {kind.upper()} IF EXISTS {quote(name)};')
# RESTRICT is immediate even with deferred FK checking. Remove only project-linked
# children here; their exact rows and descendants are restored from the snapshots.
for name in children:
    for fk in db.execute('PRAGMA foreign_key_list(' + quote(name) + ')'):
        if fk[2] == 'projects' and fk[6] == 'RESTRICT':
            lines.append(f'DELETE FROM {quote(name)} WHERE {quote(fk[3])} IS NOT NULL;')
lines += [new_sql + ';', 'INSERT INTO _project_client_0091 SELECT * FROM projects;', 'DROP TABLE projects;', 'ALTER TABLE _project_client_0091 RENAME TO projects;']
for (sql,) in db.execute("SELECT sql FROM sqlite_schema WHERE type='index' AND tbl_name='projects' AND sql IS NOT NULL ORDER BY name"):
    lines.append(sql + ';')
for name in children:
    columns = list(db.execute('PRAGMA table_info(' + quote(name) + ')'))
    names = [r[1] for r in columns]
    primary = [r[1] for r in sorted(columns,key=lambda r:r[5]) if r[5]]
    assert primary, name
    fields = ','.join(map(quote,names))
    updates = ','.join(f'{quote(n)}=excluded.{quote(n)}' for n in names if n not in primary)
    lines.append(f'INSERT INTO {quote(name)}({fields}) SELECT {fields} FROM {quote("_p0091_"+name)} WHERE true ON CONFLICT({",".join(map(quote,primary))}) DO UPDATE SET {updates};')
    lines.append(f'INSERT INTO _project_0091_assert SELECT CASE WHEN EXISTS(SELECT {fields} FROM {quote("_p0091_"+name)} EXCEPT SELECT {fields} FROM {quote(name)}) OR (SELECT count(*) FROM {quote(name)})<>(SELECT count(*) FROM {quote("_p0091_"+name)}) THEN 0 ELSE 1 END;')
for _,_,_,sql in objects:
    lines.append(sql + ';')
lines.append("CREATE TRIGGER project_client_cannot_clear BEFORE UPDATE OF client_id ON projects WHEN OLD.client_id IS NOT NULL AND NEW.client_id IS NULL BEGIN SELECT RAISE(ABORT,'client_workspace_client_required'); END;")
lines.append('INSERT INTO _project_0091_assert SELECT CASE WHEN EXISTS(SELECT 1 FROM pragma_foreign_key_check) THEN 0 ELSE 1 END;')
for name in children: lines.append(f'DROP TABLE {quote("_p0091_"+name)};')
lines += ['DROP TABLE _project_0091_assert;', 'PRAGMA defer_foreign_keys=OFF;', '']
output = root / 'cloudflare/d1/migrations/0091_optional_project_client.sql'
content = '\n'.join(lines)
if output.exists() and output.read_text() != content:
    raise SystemExit('Existing migration differs; never overwrite a released migration.')
output.write_text(content)
print(f'{len(children)} dependent tables preserved; {len(content)} bytes.')
